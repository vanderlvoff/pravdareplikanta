"""Rebuild owner-requested press derivatives; never modify supplied medal files.

Install processing tools: python -m pip install -e '.[artwork]'
Run from the repository root: python scripts/process_medals.py
"""

import hashlib
import json
from pathlib import Path

from PIL import Image, ImageEnhance, ImageFilter, ImageOps

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets"
OUTPUT = ASSETS / "medals/press"
NAMES = (("jupiter", "jpeg", 32.0), ("tannhauser", "png", 32.0), ("orion", "jpeg", 35.175))
BAYER = ((0, 8, 2, 10), (12, 4, 14, 6), (3, 11, 1, 9), (15, 7, 13, 5))


def grayscale(path: Path) -> Image.Image:
    """Composite transparent artwork on paper before processing."""
    with Image.open(path) as original:
        rgba = original.convert("RGBA")
        paper = Image.new("RGBA", rgba.size, "white")
        paper.alpha_composite(rgba)
        return paper.convert("L")


def press_image(gray: Image.Image) -> Image.Image:
    """High contrast ink with ordered halftone; strictly black and white pixels."""
    image = gray.resize((512, 512), Image.Resampling.LANCZOS)
    image = ImageOps.autocontrast(image, cutoff=1)
    image = ImageEnhance.Contrast(image).enhance(1.8)
    image = image.filter(ImageFilter.UnsharpMask(radius=1, percent=120, threshold=3))
    pixels = image.load()
    result = Image.new("1", image.size)
    result.putdata(
        [
            255 if pixels[x, y] > 80 + BAYER[(y // 2) % 4][(x // 2) % 4] * 9 else 0
            for y in range(image.height)
            for x in range(image.width)
        ]
    )
    return result


def main() -> None:
    OUTPUT.mkdir(parents=True, exist_ok=True)
    spacing = ["/* Generated by scripts/process_medals.py: halve visible horizontal gaps. */"]
    for lang in ("ru", "en", "ja"):
        previous_right = 0.0
        for index, (name, extension, width) in enumerate(NAMES):
            gray = grayscale(ASSETS / f"medals/{lang}/{name}_{lang}.{extension}")
            bounds = gray.point(lambda value: 255 if value < 225 else 0).getbbox()
            if bounds is None:
                raise ValueError(f"Empty medal: {lang}/{name}")
            if index:
                # CSS gap is zero: blank image margins provide all visible spacing.
                gap = previous_right + width * bounds[0] / gray.width
                spacing.append(
                    f".medals:lang({lang}) .medal-{name} {{ margin-left: -{gap / 2:.6f}%; }}"
                )
            previous_right = width * (1 - bounds[2] / gray.width)
            press_image(gray).save(OUTPUT / f"{name}_{lang}.png", optimize=False)
    (OUTPUT / "spacing.css").write_text("\n".join(spacing) + "\n", encoding="utf-8")
    manifest_path = ASSETS / "MANIFEST.json"
    entries = json.loads(manifest_path.read_text(encoding="utf-8"))
    entries = [entry for entry in entries if not entry["path"].startswith("medals/press/")]
    entries.extend(
        {
            "path": str(path.relative_to(ASSETS)),
            "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
        }
        for path in sorted(OUTPUT.iterdir())
        if path.is_file()
    )
    manifest_path.write_text(json.dumps(entries, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
